export const SPINE_KEYS = ['goal', 'need', 'view', 'fear', 'face'];
export const SPINE_NAME = { goal: 'Чего добивается — по собственному мнению', need: 'Что нужно на самом деле', view: 'Мировоззрение: как устроены мир и люди', fear: 'Чего боится больше всего', face: 'Как хочет выглядеть в чужих глазах' };

/** Привести стержень к рабочему виду. */
export function normSpine(x) {
    const out = {};
    for (const k of SPINE_KEYS) out[k] = typeof x?.[k] === 'string' ? x[k].replace(/\s+/g, ' ').trim().slice(0, 180) : '';
    return out;
}
export const hasSpine = (sp) => !!sp && SPINE_KEYS.some(k => sp[k]);

/**
 * Стержень строкой для модели. Сверхзадача (Станиславский) — то, чего человек добивается всей жизнью; у живого
 * персонажа она расходится с тем, что ему на самом деле нужно (у сценаристов — «хочу» против «нужно»), и пока
 * не припрёт, он выбирает первое. Пять полей разложены по трём положениям, чтобы не сыпать всё разом:
 *   'calm'   — тихая сцена: чем живёт (видно в мелочах);
 *   'choice' — он сейчас решает: «хочу» против «нужно» и главный страх. seeing — 0…2: «хочу» растёт из убеждения
 *              о себе, поэтому пока оно крепко — человек выбирает «хочу»; шатается (1) — начинает видеть, что
 *              ему нужно; сломалось (2) — впервые может выбрать «нужно», даже ценой «хочу»;
 *   'press'  — прижало всерьёз: через что он читает происходящее, чего боится и какое лицо держит.
 */
export function spineLine(sp, mode = 'press', seeing = false) {
    if (!hasSpine(sp)) return '';
    if (mode === 'calm') return sp.goal ? `чем живёт: ${sp.goal} — пусть это будет видно в мелочах и в том, что делает первым` : '';
    const bits = [];
    if (mode === 'choice') {
        if (sp.goal) bits.push(`решает из своего «хочу»: ${sp.goal}`);
        const see = ['этого пока не видит и выбирает первое', 'уже начинает это видеть, и выбор даётся с трудом', 'теперь видит это и впервые может выбрать второе, даже ценой первого'][Math.max(0, Math.min(2, Number(seeing) || 0))];
        if (sp.need) bits.push(`на деле нужно другое: ${sp.need} — ${see}`);
        if (sp.fear) bits.push(`больше всего боится: ${sp.fear}`);
        return bits.join('; ');
    }
    if (sp.view) bits.push(`происходящее читает через своё: ${sp.view}`);
    if (sp.fear) bits.push(`больше всего боится: ${sp.fear}`);
    if (sp.face) bits.push(`и сейчас держит лицо: хочет выглядеть ${sp.face}`);
    return bits.join('; ');
}
