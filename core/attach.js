// Брак — не сценарий пары, а её положение: троп и способ привязываться остаются какими были, брак ложится сверху.
// Что он меняет на деле: у связанных обязательством «я» в речи и в голове становится «мы» (Agnew et al., 1998), а на
// выпад своего человека чаще отвечают не выпадом, а сглаживанием (Rusbult et al., 1991). Чисел брак не трогает:
// «после медового месяца остывает» — среднее по выборке, у большинства пар первые годы ровные (Lavner, Bradbury,
// 2010; Williamson, Lavner, 2020), и остужать или подслащивать связь по календарю мозг не должен.
// Считает он одно — сколько они женаты на день истории: по дате свадьбы.

/** Дата свадьбы к рабочему виду: 'ГГГГ-ММ-ДД' | 'ГГГГ' | 'yes' (женаты, дата неизвестна) | '' (не женаты). */
export function wedNorm(v) {
    if (v === true) return 'yes';
    const t = String(v ?? '').trim().toLowerCase();
    if (!t) return '';
    let m = t.match(/^(\d{4})-(\d{1,2})-(\d{1,2})$/);
    if (!m) { const r = t.match(/^(\d{1,2})\.(\d{1,2})\.(\d{4})$/); if (r) m = [r[0], r[3], r[2], r[1]]; }
    if (m) {
        const mo = +m[2], d = +m[3];
        return mo >= 1 && mo <= 12 && d >= 1 && d <= 31 ? `${m[1]}-${String(mo).padStart(2, '0')}-${String(d).padStart(2, '0')}` : '';
    }
    if (/^\d{4}$/.test(t)) return t;
    return ['yes', 'да', 'true', 'женаты', 'в браке'].includes(t) ? 'yes' : '';
}
const plural = (n, f) => { const a = Math.abs(n) % 100, b = a % 10; return f[a > 10 && a < 20 ? 2 : b === 1 ? 0 : b >= 2 && b <= 4 ? 1 : 2]; };
const isoParts = (t) => { const m = String(t || '').match(/^(\d{4})-(\d{2})-(\d{2})$/); return m ? [+m[1], +m[2], +m[3]] : null; };
/**
 * Сколько они женаты на день истории today ('ГГГГ-ММ-ДД' или '' — день неизвестен).
 * → null — не женаты или на этот день ещё не женаты (чат прошлой эпохи);
 *   { stage: 'fresh' (первый год) | 'mid' | 'long' (от пяти лет) | '' (срок неизвестен), text: «3 дня», days, years }.
 * Границы «первый год» и «от пяти лет» — условность для слов, а не находка из исследований.
 */
export function wedSpan(wed, today = '') {
    const w = wedNorm(wed);
    if (!w) return null;
    const T = isoParts(today);
    if (w === 'yes' || !T) return { stage: '', text: '', days: null, years: null };
    if (w.length === 4) {
        const years = T[0] - +w;
        if (years < 0) return null;
        return years === 0 ? { stage: 'fresh', text: 'первый год', days: null, years: 0 } : { stage: years >= 5 ? 'long' : 'mid', text: `${years} ${plural(years, ['год', 'года', 'лет'])}`, days: null, years };
    }
    const W = isoParts(w);
    const days = Math.round((Date.UTC(T[0], T[1] - 1, T[2]) - Date.UTC(W[0], W[1] - 1, W[2])) / 864e5);
    if (days < 0) return null;
    const years = T[0] - W[0] - (T[1] < W[1] || (T[1] === W[1] && T[2] < W[2]) ? 1 : 0);
    let text;
    if (days === 0) text = 'с сегодняшнего дня';
    else if (days < 14) text = `${days} ${plural(days, ['день', 'дня', 'дней'])}`;
    else if (days < 60) { const n = Math.floor(days / 7); text = `${n} ${plural(n, ['неделю', 'недели', 'недель'])}`; }
    else if (years < 1) { const n = Math.max(2, Math.floor(days / 30.44)); text = `${n} ${plural(n, ['месяц', 'месяца', 'месяцев'])}`; }
    else text = `${years} ${plural(years, ['год', 'года', 'лет'])}`;
    return { stage: years < 1 ? 'fresh' : years >= 5 ? 'long' : 'mid', text, days, years };
}
/** Годовщина свадьбы: сколько лет исполняется в день today (0 — сегодня не годовщина). Только при полной дате. */
export function wedDay(wed, today = '') {
    const W = isoParts(wedNorm(wed)), T = isoParts(today);
    return W && T && W[1] === T[1] && W[2] === T[2] && T[0] > W[0] ? T[0] - W[0] : 0;
}
