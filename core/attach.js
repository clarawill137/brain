/** Множители тропа для событий hits (сила ≤ 2). */
export function tropeMul(id, hits) {
    const M = TROPE_KMUL[id];
    const out = {};
    if (!M || !hits) return out;
    for (const [k, n] of Object.entries(hits)) if (M[k] && Math.round(n) >= 1 && Math.round(n) <= 2) out[k] = M[k];
    return out;
}
