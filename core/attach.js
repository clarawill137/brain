/** Способ по id или по названию («намертво», «сторож»…): так можно писать руками. */
export function styleId(v) {
    const t = String(v || '').trim().toLowerCase();
    if (!t) return '';
    if (STYLES[t]) return t;
    return STYLE_IDS.find(k => STYLES[k].name.toLowerCase() === t || t.startsWith(STYLES[k].name.toLowerCase().slice(0, 5))) || '';
}
