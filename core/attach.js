// Код-мозг — как привязываются. Две стороны, которые потом совмещаются:
//   1) сторона человека — его способ привязываться (у каждого свой) и то, насколько в нём сидит рана отвержения;
//   2) сторона пары — троп: по какому сценарию эти двое существуют вместе.
// Способы — не диагнозы, а игровые краски, но стоят они на двух вещах из исследований привязанности:
// при угрозе связи человек либо «накручивает» систему привязанности (цепляется, требует, проверяет),
// либо «глушит» её (дистанция, самодостаточность, чувства потом), либо мечется между тем и другим
// (Mikulincer, Shaver, 2003); а чувствительный к отвержению заранее его ждёт, видит в двусмысленном и
// отвечает слишком сильно — враждой, уходом или угождением (Downey, Feldman, 1996).
// Два «родительских» способа (0.14) — про любовь с условием: расположение дают за то, что человек соответствует,
// и отнимают, когда нет; выросший так делает нужное, но изнутри это принуждение и обида на того, кто растил
// (Assor, Roth, Deci, 2004; Roth et al., 2009). Чередование тепла и боли при неравной силе привязывает прочнее
// ровного тепла (Dutton, Painter, 1993) — отсюда «тепло всегда с уроком внутри».
// Тропы пар — из вымысла (см. claude/brain/FICTION.md). Чистые данные и функции: без Таверны, Life и DOM.

