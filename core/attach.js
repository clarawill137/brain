/** 'high' | 'low' | '' — как человек держится обычно. */
export function statusHabit(temper, style = '') {
    const x = num(temper?.base?.ctl) + 0.5 * num(temper?.base?.wor) + num(STYLE_STATUS[style]);
    return x >= 12 ? 'high' : x <= -12 ? 'low' : '';
}
/**
 * Качели статуса: привычно уверенного придавило стыдом или страхом — 'drop'; привычно тихого вынесло наверх
 * злостью, куражом или победой — 'rise'. Иначе ''. dom — ведущее чувство { id, step }, won — была ли только что победа.
 */
export function statusFlip(habit, dom, won = false) {
    const st = Math.round(num(dom?.step));
    if (habit === 'high' && (dom?.id === 'shame' || dom?.id === 'fear') && st >= 2) return 'drop';
    if (habit === 'low' && ((dom?.id === 'anger' && st >= 2) || (dom?.id === 'playful' && st >= 2) || won)) return 'rise';
    return '';
}

