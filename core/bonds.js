// Код-мозг — привязанности. Чувства к конкретному человеку здесь не счёт «ты мне — я тебе»: любовь — линза,
// через которую он видит всё, что от этого человека приходит. Мелкое плохое она размывает и не даёт ему осесть,
// тепло делает теплее, а вот уход, предательство и соперника — больнее: терять есть что.
// Откуда это: «перевес чувства» (Weiss, Gottman) — в ладу партнёры читают резкость мягче, чем сторонний наблюдатель,
// а когда накопилось — и нейтральное читают уколом; общинные отношения (Clark, Mills) — близкие дают по нужде,
// а не в долг; регуляция риска (Murray, Holmes, Collins) — тянуться или закрываться решает уверенность в том, что
// тебя ценят; социальная регуляция угрозы (Coan) — рядом со своим человеком угроза переносится легче.
// Шкалы пары (0…100) приходят из Life; «Любовь» там ставит игрок и запирает. Чистая математика.

import { clamp } from './psyche.js';

const num = (v, d = 0) => (Number.isFinite(+v) ? +v : d);
const r2 = (v) => Math.round(v * 100) / 100;
const pct = (v) => Math.round(100 * clamp(v, 0, 1));

export const SOFT = ['blow', 'wrong', 'bound'];      // то, что любовь размывает, пока оно некрупное
export const GLOW = ['warm', 'open', 'calm'];        // то, что от своего человека греет сильнее

/**
 * Чувства who → к этому человеку долями 0…1 и сила привязанности L.
 * Названная любовь (шкала «Любовь») — это L напрямую. Без неё привязанность собирается из близости и доверия,
 * но не выше 0.8: дружба тоже держит, а единицу даёт только любовь.
 */
export function tie(rel) {
    if (!rel || typeof rel !== 'object') return null;
    const f = (k, d = 0) => clamp(num(rel[k], d), 0, 100) / 100;
    const love = f('love'), close = f('closeness', 50), trust = f('trust', 50);
    const grown = clamp((0.7 * close + 0.3 * trust - 0.5) / 0.5, 0, 1) * 0.8;
    return {
        love, close, trust, want: f('desire'), jeal: f('jealousy'), tens: f('tension'), guilt: f('guilt'),
        L: r2(Math.max(love, grown)),
        fixed: Number.isFinite(rel.pin?.love),
        // «накопилось»: напряжение в паре выше 55 начинает перекрашивать всё, что от него приходит
        sour: r2(clamp((f('tension') - 0.55) / 0.35, 0, 1)),
    };
}

/**
 * Умные статы пары — пересчитываются каждый пост из шкал Life и его собственного состояния (0…100):
 *   blur  — «прощает»: сколько мелкого плохого от этого человека размоется;
 *   haven — «гавань»: насколько рядом с ним отпускает;
 *   fuse  — «ревность наготове»: насколько его возьмёт появление соперника;
 *   dread — «страх потерять».
 * v: { E — оси сейчас, dr — потребности, bel — носит ли убеждение, что его не за что любить (0…1) }.
 */
export function pairStats(t, v = {}) {
    if (!t) return { blur: 0, haven: 0, fuse: 0, dread: 0 };
    const wor = num(v.E?.wor), bond = num(v.dr?.bond, 60);
    // неуверенность в себе и в своём месте рядом: низкая самооценка, голод по близости, убеждение «меня не за что»
    const insecure = clamp(clamp((-wor - 10) / 60, 0, 1) * 0.55 + clamp((45 - bond) / 45, 0, 1) * 0.25 + clamp(num(v.bel), 0, 1) * 0.3, 0, 1);
    const calm = 1 - t.sour;
    return {
        blur: pct(t.L * (0.5 + 0.5 * t.trust) * calm),
        haven: pct(t.L * (0.4 + 0.6 * t.trust) * calm),
        fuse: pct(t.L * (0.3 + 0.7 * insecure) + 0.4 * t.jeal * t.L),
        dread: pct(t.L * (0.15 + 0.85 * insecure)),
        insecure: r2(insecure),
    };
}

/**
 * Линза: чем событие становится, если оно пришло от этого человека.
 * hits — { вид: сила }, t — tie(), st — pairStats().
 * → { kmul: { вид: множитель }, kmood: { вид: доля оседания в настроении }, tags: [] }
 * Метки: blur — размыло, glow — от своего теплее, deep — от своего глубже, sour — накопилось, surprise — не ждал добра.
 * Поручень: линза не усиливает то, что и так сильное (3), — одно событие не должно уносить на последнюю ступень.
 */
export function lens(hits, t, st) {
    const out = { kmul: {}, kmood: {}, tags: [] };
    if (!t || !hits) return out;
    const tag = (x) => { if (!out.tags.includes(x)) out.tags.push(x); };
    const L = t.L, b = num(st?.blur) / 100;
    for (const [k, n0] of Object.entries(hits)) {
        const n = Math.round(clamp(n0, 0, 3));
        if (!n) continue;
        if (GLOW.includes(k)) {
            if (k === 'warm' && n >= 2 && t.trust < 0.3 && L < 0.3) { out.kmul[k] = 1.25; tag('surprise'); }   // добра от него не ждал — цепляет сильнее
            else if (L >= 0.3) { out.kmul[k] = r2(1 + 0.3 * L * (1 - t.sour)); if (L >= 0.5 && t.sour < 0.5) tag('glow'); }
        } else if (k === 'loss') {
            // уход своего человека: заметный — бьёт сильнее, сильный — не выше (он и так на потолке одного события),
            // но в обоих случаях оседает глубже и держится дольше
            if (L > 0) { if (n <= 2) out.kmul[k] = r2(1 + 0.2 * L); out.kmood[k] = r2(1 + (n >= 3 ? 0.25 : 0.3) * L); }
            if (L >= 0.5) tag('deep');
        } else if (SOFT.includes(k)) {
            // сильное от своего любовь не размывает — и не усиливает: оно и так на потолке одного события.
            // Что оно пришло от своего, скажется потом: закроется он или пойдёт мириться (afterHurt)
            if (n >= 3) { if (L >= 0.5) tag('deep'); }
            else if (t.sour >= 0.5) { out.kmul[k] = r2(1 + 0.2 * t.sour); tag('sour'); }                // накопилось: и мелочь читается уколом
            else if (b > 0) { out.kmul[k] = r2(1 - 0.45 * b); out.kmood[k] = r2(1 - 0.6 * b); if (b >= 0.4) tag('blur'); }
        } else if (k === 'rival') {
            out.kmul[k] = jealMul(st);
        }
    }
    return out;
}

/** Насколько его берёт соперник: без привязанности почти никак, с любовью и неуверенностью — в полную силу. */
export const jealMul = (st) => r2(clamp(0.25 + 1.1 * num(st?.fuse) / 100, 0.25, 1.35));

/**
 * Гавань: свой человек рядом, и между ними не накопилось. → { threat — множитель угрозы, ease — сколько
 * напряжения снимает за час, safe — сколько безопасности добавляет за час }. worry — он сам сейчас за него боится:
 * тогда близость не успокаивает.
 */
export function haven(st, worry = false) {
    const h = worry ? 0 : num(st?.haven) / 100;
    return { threat: r2(1 - 0.25 * h), ease: r2(1.2 * h), safe: r2(2 * h), on: h >= 0.35 };
}

/**
 * Тянуться или закрыться после того, как от своего человека прилетело (регуляция риска):
 * уверен, что его ценят, — идёт мириться первым; не уверен — отступает первым, чтобы не отвергли.
 * → 'mend' | 'guard' | ''
 */
export function afterHurt(t, st) {
    if (!t || t.L < 0.5) return '';
    return num(st?.insecure) >= 0.5 ? 'guard' : 'mend';
}
