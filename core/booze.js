// Код-мозг — алкоголь и похмелье. Опьянение считается, а не «упоминается»: сколько выпил, как его берёт,
// на какой он стадии, что будет наутро. Опора:
//   • «алкогольная близорукость» (Steele, Josephs, 1990; Giancola и др., 2010): спиртное не «растормаживает»,
//     а сужает внимание до самого заметного. Что было на первом плане — то и разрастается: в компании ему
//     веселее, одному с тяжёлыми мыслями — хуже; далёкие последствия пропадают из виду;
//   • похмелье начинается, когда алкоголь уходит, сильнее всего — около нуля, и держится до суток; кроме
//     тела — раздражительность, тревога («хэнгзайети», тяжелее у тревожных и у тех, кто пил, чтобы заглушить),
//     вина и провалы во внимании; часть людей похмелья не знает вовсе.
// Чистая математика: без Таверны, Life и DOM.

import { clamp } from './psyche.js';

const num = (v, d = 0) => (Number.isFinite(+v) ? +v : d);
const r1 = (v) => Math.round(v * 10) / 10;

export const STAGE_AT = [12, 30, 55, 80];
export const STAGE_NAME = ['ни в одном глазу', 'навеселе', 'под градусом', 'сильное опьянение', 'в дрова'];
const DOSE = [0, 14, 28, 45];          // что добавляет «выпил» силы 1…3 обычному человеку
export const BURN = 7;                 // уходит за час у обычного человека (стадия «навеселе» — за пару часов)

/** Стадия опьянения 0…4 по тому, сколько в нём сейчас. */
export function stageOf(bac) {
    let st = 0;
    for (const edge of STAGE_AT) if (num(bac) >= edge) st++;
    return st;
}
/** Как его берёт: 1 — как всех; 0.6 — пьянеет с бокала; 4 — суперсолдат, почти не берёт. */
export const tolOf = (temper) => clamp(num(temper?.booze, 1), 0.4, 6);

/**
 * Выпил: n — 1 (бокал-другой), 2 (заметно), 3 (много). k — доля порции: когда человек тянет тот же бокал из поста
 * в пост, каждый следующий глоток — не новая порция целиком. Возвращает, сколько прибавилось.
 */
export function drink(s, n, tol = 1, k = 1) {
    const add = DOSE[Math.round(clamp(n, 0, 3))] * clamp(k, 0.1, 1) / clamp(tol, 0.4, 6);
    if (!add) return 0;
    s.bac = clamp(num(s.bac) + add, 0, 100);
    s.bacPeak = Math.max(num(s.bacPeak), s.bac);
    if (stageOf(s.bac) >= 3) s.blank = true;      // с третьей стадии вечер запомнится кусками
    return r1(add);
}

/**
 * Прошло hours часов: алкоголь уходит; когда его осталось меньше трети от пика (а пик был настоящим) —
 * начинается похмелье: полсуток обычное, почти сутки тяжёлое. Длинный пропуск времени съедает его часть или всё
 * («проспался»). Тем, кого почти не берёт (tol ≥ 3), похмелье не грозит.
 */
export function sober(s, hours, tol = 1) {
    const h = clamp(hours, 0, 24 * 30);
    if (s.hung) { s.hung.left = num(s.hung.left) - h; if (s.hung.left <= 0) { s.hung = null; s.blank = false; } }
    const bac0 = num(s.bac), peak = num(s.bacPeak);
    if (!bac0 && !peak) return s;
    const rate = BURN * clamp(tol, 0.4, 6);
    s.bac = Math.max(0, bac0 - rate * h);
    const edge = peak * 0.35;
    if (peak >= 40 && tol < 3 && s.bac <= edge) {
        const lvl = peak >= 70 ? 2 : 1;
        const since = bac0 > edge ? h - (bac0 - edge) / rate : h;       // сколько уже прошло с начала спада
        const left = (lvl === 2 ? 22 : 13) - Math.max(0, since);
        if (left > 0 && (!s.hung || num(s.hung.lvl) < lvl)) s.hung = { lvl, left: r1(left), peak: Math.round(peak) };
        s.bacPeak = 0;
    }
    if (s.bac <= 0) { s.bacPeak = 0; if (!s.hung) s.blank = false; }
    return s;
}

/**
 * Что опьянение и похмелье делают с ним сейчас. v: { company — рядом люди, с которыми ему хорошо или просто есть
 * на кого смотреть; heavy — на первом плане у него тяжёлое (ведёт плохое чувство); prone — насколько он тревожен
 * и не уверен в себе (0…1): таким похмельная тревога достаётся сильнее }.
 * → { stage, hung, off: сдвиг осей, amp — во сколько раз разрастается то, что на первом плане, threat — множитель
 *     угрозы, loose — скрываемое лезет наружу, drain — держать лицо дороже, bold — далёкие последствия не видны,
 *     blank — завтра не вспомнит, raw, willCap, strainIn, list: [{ id, text }] }
 */
export function boozeNow(s, v = {}) {
    const stage = stageOf(s.bac);
    const hung = s.hung ? Math.round(clamp(s.hung.lvl, 1, 2)) : 0;
    const out = { stage, hung, off: { val: 0, aro: 0, ctl: 0, wor: 0 }, amp: 1, threat: 1, loose: false, drain: 0, bold: false, blank: false, raw: 1, willCap: 100, strainIn: 0, list: [] };
    if (stage) {
        // близорукость: первый план разрастается, фон пропадает
        out.amp = 1 + 0.14 * stage;
        out.loose = true;
        out.drain = 0.25 * stage;
        out.bold = stage >= 2;
        out.blank = stage >= 3;
        // ось «контроль» — про ощущение беспомощности, а не про тормоза: её спиртное трогает слабо. Тормоза — это loose и drain
        out.off.ctl = -3 * stage;
        // заряд: сначала вверх, с третьей стадии — вниз (клонит, язык заплетается)
        out.off.aro = stage <= 2 ? 5 * stage : -8 * (stage - 2);
        // настроение идёт за тем, что на первом плане: в компании — теплее, одному с тяжёлым — темнее
        out.off.val = v.heavy ? -4 * stage : v.company ? 4 * Math.min(stage, 2) : 0;
        // страх глушит только когда есть на что отвлечься; наедине с тяжёлым — наоборот
        out.threat = v.heavy && !v.company ? 1 + 0.08 * stage : 1 - 0.1 * stage;
        out.list.push({ id: 'drunk', text: STAGE_NAME[stage] });
    }
    if (hung) {
        const anx = clamp(num(v.prone), 0, 1);
        out.off.val -= 7 * hung;
        out.off.aro -= 9 * hung;
        out.off.ctl -= Math.round(4 * hung * (0.5 + anx));       // похмельная тревога — тяжелее у тревожных
        out.off.wor -= Math.round(5 * hung * anx);               // и вина за вчерашнее
        out.raw = 1 + 0.15 * hung;
        out.willCap = 90 - 15 * hung;
        out.strainIn = 0.4 * hung;
        out.list.push({ id: 'hung', text: hung === 2 ? 'тяжёлое похмелье' : 'похмелье' });
    }
    return out;
}

