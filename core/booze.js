/**
 * Подсказки игроку про его персонажа: что это за стадия, когда выветрится, чего ждать наутро.
 * s — состояние (bac, bacPeak, hung, blank), tol — переносимость. → строки (может быть пусто).
 */
export function playerTips(s, tol = 1) {
    const out = [];
    const stage = stageOf(s?.bac);
    const k = clamp(tol, 0.4, 6);
    if (stage) {
        out.push(TIP[stage]);
        out.push(`если больше не пить — выветрится примерно за ${Math.max(1, Math.round(num(s.bac) / (BURN * k)))} ч истории`);
        const peak = Math.max(num(s.bacPeak), num(s.bac));
        out.push(k >= 3 ? 'похмелья не будет' : peak >= 70 ? 'наутро — тяжёлое похмелье, почти на сутки' : peak >= 40 ? 'наутро — похмелье, на полдня' : 'похмелья с такого не будет');
    }
    if (s?.hung) out.push(`похмелье ещё ~${Math.max(1, Math.round(num(s.hung.left)))} ч истории: свет, звук, тошнота; раздражительность и тревога без причины — если захочешь сыграть`);
    if (s?.blank && (stage >= 3 || s?.hung)) out.push('по счёту вечер должен помниться кусками — можно сыграть провал');
    return out;
}
