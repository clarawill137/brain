/** Кассета для эмоции id на ступени step (1…): своя из темперамента, иначе запасная. */
export function cassOf(temper, id, step) {
    const n = Math.max(1, Math.min(step, EMO_STEPS[id] || 1)) - 1;
    const own = Array.isArray(temper?.cass?.[id]) ? String(temper.cass[id][n] || '').trim() : '';
    return own || CASS[id]?.[n] || '';
}

export function cassText(temper, key) {
    const own = typeof temper?.cass?.[key] === 'string' ? temper.cass[key].trim() : '';
    return own || CASS[key] || '';
}

/** Кассеты из текста (по ступени на строку) и обратно — для правки руками. */
export function cassLines(temper, id) {
    const n = EMO_STEPS[id] || 0;
    return Array.from({ length: n }, (_, k) => cassOf(temper, id, k + 1));
}
export function parseLines(text, id) {
    const n = EMO_STEPS[id] || 0;
    const rows = String(text || '').split(/\n+/).map(x => x.replace(/^\s*\d+[.)]\s*/, '').trim()).filter(Boolean).slice(0, n);
    return rows.map(x => x.slice(0, 260));
}

/** Принять кассеты, которые выписала модель: только известные ключи, нужное число строк. */
export function cleanCass(raw) {
    const out = {};
    if (!raw || typeof raw !== 'object') return out;
    for (const [id, n] of Object.entries(EMO_STEPS)) {
        const rows = (Array.isArray(raw[id]) ? raw[id] : []).map(x => String(x || '').trim().slice(0, 260)).filter(x => x.length > 8).slice(0, n);
        if (rows.length) out[id] = rows;
    }
    for (const k of SINGLES) { const t = typeof raw[k] === 'string' ? raw[k].trim().slice(0, 320) : ''; if (t.length > 8) out[k] = t; }
    return out;
}

/** Как держится убеждение — словами для модели. truth — что стало правдой, когда оно сломалось. */
export function beliefText(b, band) {
    if (band === 3) return `живёт с убеждением «${b.t}» — оно держится крепко: доброе о себе принимает с трудом, чаще не верит`;
    if (band === 2) return `убеждение «${b.t}» шатается: ловит себя на сомнении — а так ли это`;
    if (band === 1) return `убеждение «${b.t}» почти не держит — осталась привычка так думать, и та слабеет`;
    return b.truth ? `прежнее «${b.t}» больше не правда; теперь знает: ${b.truth}` : `прежнее «${b.t}» больше не правда`;
}
