// Код-мозг — подсказки игроку. Не для модели: это шпаргалка тебе, как с человеком сейчас обращаться —
// что сработает, что добьёт и чего ждать. Собирается из того же состояния, что и заметка модели.
// Чистая функция: без Таверны, Life и DOM. Тексты без рода — подходят любому персонажу.

import { willBand, beliefHp, rawNerves, nightChance, roleBand } from './psyche.js';
import { hungriest } from './drives.js';

const BY_EMO = {
    fear: 'страх: верни контроль — дай выбор или простую задачу, говори ровно и коротко',
    anger: 'злость: не дожимай — дай уйти и вернуться; выплеснуть её не поможет, гасит то, что успокаивает тело',
    shame: 'стыд: слова отскакивают — показывай делом; похвала сейчас оседает вполсилы',
    low: 'тоска: просто будь рядом, без вопросов и «взбодрись»',
};
const BY_DRIVE = {
    bond: 'не хватает близости: касание, сесть рядом, остаться ещё на минуту',
    safe: 'не хватает безопасности: тише, без резкого, замки проверены, никто не подойдёт со спины',
    free: 'тесно: предложи выбор вместо готового решения, спроси, а не скажи',
    need: 'хочется быть нужным: попроси о помощи, дай дело для рук',
    quiet: 'людей слишком много: уведи туда, где тихо',
    novel: 'рутина давит: позови куда-нибудь, затей что-то новое',
};
const SORE = { warm: '', threat: 'угроза', blow: 'удары по самооценке', bound: 'потеря контроля', wrong: 'несправедливость и ложь', loss: 'разлука и отвержение' };

/**
 * v: { s, t, dom, leak, fore: { breakIn, rawIn, calmIn }, apart, dear, mine, feeder, hurt } → { help: [], hurt: [], expect: [] }
 * apart — он сейчас не рядом с героиней игрока. dear — { name, st } его «свой человек» и умные статы пары;
 * dear.sour — насколько между ними накопилось (0…1); dear.cosmic — привязанность космическая; mine — этот человек и есть
 * героиня игрока; worry — он сейчас за него боится; grudge — на кого держит обиду (имена); feeder — { name, drive } кто обычно утоляет самую голодную потребность;
 * hurt — что он делает после того, как от своего прилетело ('mend' | 'guard').
 * booze — { stage, hung, blank } опьянение и похмелье; spine — стержень из темперамента;
 * ease — что помогает при его способе привязываться; mute — не согласен со своим человеком и молчит ('mute' | 'cold' | 'fight' | 'control').
 */
export function hints(v) {
    const { s, t, dom } = v;
    const help = [], hurt = [], expect = [];
    const neg = ['fear', 'anger', 'shame', 'low'].includes(dom?.id);
    const band = willBand(s.will);

    if (s.brk) expect.push('срыв в следующем ответе — словами его не остановить, нужны время и безопасность');
    // алкоголь: что на первом плане, то и разрастается
    const bz = v.booze || {};
    if (bz.stage >= 3) help.push('сильное опьянение: серьёзного разговора не выйдет, а завтра не вспомнит — уложи, дай воды, главное оставь на утро');
    else if (bz.stage >= 1) help.push(neg
        ? 'под градусом, а на душе тяжело: спиртное сейчас раздувает именно это — не оставляй наедине с этими мыслями, переключи на себя'
        : 'под градусом: скажет больше обычного и решится на то, на что на трезвую голову не хватает духу, — хороший момент спросить о важном');
    if (bz.hung) help.push('с похмелья: тише, вода, еда и никаких разборов вчерашнего до обеда');
    if (bz.hung && bz.blank) expect.push('вчерашний вечер помнит кусками: может спросить, что говорил и делал');
    if (neg && BY_EMO[dom.id]) help.push(BY_EMO[dom.id]);
    // привязанность: через что он видит своего человека. Сначала острое — что между ними прямо сейчас
    const d = v.dear, st = d?.st;
    const jealous = s.jeal >= 25;
    const quiet = !jealous && !v.hurt;
    if (v.hurt === 'stay') help.push(v.mine ? 'ему больно от того, что ты сделала, и он может сказать это в лицо — но для тебя сделает всё то же: это ничего не меняет' : 'ему больно от своего человека, но он остаётся рядом: это ничего не меняет');
    if (v.hurt === 'guard') help.push(v.mine ? 'после твоих слов — в глухой обороне и навстречу не пойдёт: шаг за тобой' : 'после слов своего человека — в глухой обороне: навстречу не пойдёт');
    if (v.hurt === 'mend') expect.push('сердиться долго не выйдет: скоро будет искать повод помириться');
    if (jealous) help.push(v.mine ? 'ревнует: само за час не пройдёт — скажи или покажи прямо, чьё это место' : 'ревнует: само за час не пройдёт');
    if (neg && t.fix?.length) help.push(`возвращает в себя: ${t.fix.slice(0, 4).join(', ')}`);
    if (v.leak >= 1) help.push('носит в себе несказанное: спроси прямо — сейчас может ответить');
    const hungry = hungriest(s);
    if (hungry && hungry.band <= 2 && hungry.v < 45) help.push(BY_DRIVE[hungry.id]);
    if (band <= 1) help.push('сил мало: не требуй решений и разговоров «о главном» прямо сейчас');
    const rb = roleBand(s, t);
    if (rb) help.push(`держит лицо ${s.role}-й день подряд: дай возможность не держаться — спроси и не отступай после первого «нормально»`);
    if (v.feeder && hungry && hungry.id === v.feeder.drive) help.push(`это обычно даёт ${v.feeder.name}`);
    if (d?.cosmic && quiet) help.push(v.mine ? 'простит тебе что угодно — мелкое не заметит, большое переболит и останется рядом; себе не простит, если с тобой что-то случится' : `${d.name} простит что угодно`);
    else if (st && quiet && st.blur >= 55) help.push(v.mine ? 'мелкую резкость тебе простит почти не заметив — любовь её размывает; уход и холод — нет' : `мелкую резкость от ${d.name} простит почти не заметив; уход и холод — нет`);
    if (st && quiet && v.haven) help.push(v.mine ? 'рядом с тобой отпускает само: можно просто побыть рядом' : `рядом ${d.name} — отпускает само`);
    const shaky = (t.beliefs || []).map(b => [b, beliefHp(s, b.id)]).filter(([, hp]) => hp > 0 && hp <= 40).sort((a, b) => a[1] - b[1])[0];
    if (shaky) help.push(`убеждение «${shaky[0].t}» шатается: ещё несколько поступков — и рухнет`);

    // стержень: поступок, который даёт то, что ему на самом деле нужно, доходит глубже слов
    const sp = v.spine;
    if (sp?.need && (quiet || neg)) help.push(`на деле нужно: ${sp.need} — то, что даёт это, доходит глубже любых слов`);
    if (sp?.fear) hurt.push(`главный страх: ${sp.fear}`);
    if (bz.hung) hurt.push('с похмелья любое плохое бьёт сильнее, а сил держать лицо меньше');
    // что работает именно с ним — когда связь под угрозой (поддержка должна попадать в его способ привязываться)
    if (v.ease && (neg || v.hurt || v.mute)) help.push(`с ним работает: ${v.ease}`);
    if (v.mute) help.push(v.mute === 'mute'
        ? 'с чем-то не согласен и молчит из преданности: спроси прямо и дай понять, что «нет» ничего не сломает'
        : 'с чем-то не согласен, но о главном не скажет: спроси прямо, о чём на самом деле речь');
    const sore = Object.entries(t.sens || {}).filter(([k, x]) => x >= 1.2 && SORE[k]).sort((a, b) => b[1] - a[1]).map(([k]) => SORE[k]);
    if (sore.length) hurt.push(`больные места: ${sore.slice(0, 3).join(', ')}`);
    if (st && st.fuse >= 55 && s.jeal < 25) hurt.push(v.mine ? 'ревность наготове: твоё тепло к другому у него на глазах попадёт в больное' : 'ревность наготове: чужое внимание к своему человеку попадёт в больное');
    if (st && st.dread >= 55) hurt.push(v.mine ? 'боится тебя потерять: любое «мне надо побыть без тебя» услышит как отказ' : 'боится потерять своего человека: любое отдаление читает как отказ');
    if (d && d.sour >= 0.5) hurt.push('между вами накопилось: сейчас и нейтральное слово прочтёт как укол');
    if (d?.cosmic && v.worry) hurt.push(v.mine ? 'за тебя пойдёт на что угодно и нарушит свои же правила — сейчас он опаснее всего для самого себя' : 'за своего человека пойдёт на что угодно — опаснее всего для самого себя');
    for (const n of (v.grudge || []).slice(0, 2)) expect.push(`держит обиду на ${n}: само пройдёт не скоро — нужен шаг с той стороны`);
    if (rawNerves(s)) hurt.push('нервы сырые: любое плохое бьёт сильнее, триггеры — на ступень выше');
    if (s.hang) hurt.push('после срыва: ещё один удар — и сорвётся снова');
    if (neg && s.mood[{ fear: 'ctl', anger: 'val', shame: 'wor', low: 'val' }[dom.id]] <= -16) hurt.push('настроение тяжёлое: от одной хорошей фразы не отпустит — тепло нужно несколько раз подряд');

    const f = v.fore || {};
    const hrs = (h) => (h >= 48 ? `~${Math.round(h / 24)} дн.` : `~${h} ч`);
    if (f.breakIn != null) expect.push(`если ничего не изменится — срыв через ${hrs(f.breakIn)} истории`);
    else if (f.rawIn != null) expect.push(`если ничего не изменится — через ${hrs(f.rawIn)} истории нервы станут сырыми`);
    if (f.calmIn != null && !s.brk) expect.push(`если не подливать — отпустит через ${hrs(f.calmIn)} истории`);
    if (nightChance(s, { trig: false }) >= 0.4) expect.push('ночь, скорее всего, будет плохой');
    if (v.apart && s.dr && s.dr.bond <= 35 && band >= 1) expect.push('скучает: скоро выйдет на связь первым');
    return { help: help.slice(0, 6), hurt: hurt.slice(0, 5), expect };
}
